# Code coverage — must start before any application code is loaded.
# Enabled only when COVERAGE=1 to avoid slowing down ordinary spec runs.
if ENV["COVERAGE"]
  require "simplecov"

  # SimpleCov 0.22 calls `ParallelTests.wait_for_other_processes_to_finish`
  # during result generation whenever ParallelTests is loaded; the installed
  # parallel_tests version doesn't define that method, which crashes the
  # at_exit report. In a single-process coverage run there are no sibling
  # processes to await, so stub it as a no-op when it's missing.
  begin
    require "parallel_tests"
  rescue LoadError
    nil
  end
  if defined?(ParallelTests) && !ParallelTests.respond_to?(:wait_for_other_processes_to_finish)
    def ParallelTests.wait_for_other_processes_to_finish(*); end
  end

  SimpleCov.start "rails" do
    # Per-agent isolated output dir so parallel coverage runs don't clobber.
    coverage_dir ENV.fetch("COVERAGE_DIR", "coverage")
    enable_coverage :branch
    primary_coverage :branch

    add_group "Models",       "app/models"
    add_group "Controllers",  "app/controllers"
    add_group "Services",     "app/services"
    add_group "Components",   "app/components"
    add_group "Contracts",    "app/contracts"
    add_group "Concepts",     "app/concepts"
    add_group "Helpers",      "app/helpers"
    add_group "Jobs",         "app/jobs"
    add_group "Mailers",      "app/mailers"

    # Page template payloads are excluded per project convention.
    add_filter "app/services/page_layout_templates/templates/"
    add_filter "spec/"
  end
end

