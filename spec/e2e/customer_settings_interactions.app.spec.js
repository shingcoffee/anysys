import { test, expect } from "@playwright/test"
import { BASE, ROOT, protect, visit, fixture, registerFixture, connected, fits, screenshot, payload, interceptedSubmit, handleDialog } from "./customer_settings_support.js"

const submit = form => form.locator("input[type=submit],button[type=submit]")
const params = entry => new URLSearchParams(entry.body)

test.describe("customer settings browser operations with intercepted persistence", () => {
  test.skip(!BASE, "Set APP_BASE_URL to the SKIP_AUTH=1 development server")
  test.setTimeout(120000)

  for (const locale of ["en", "zh-CN"]) {
    for (const width of [390, 1440]) {
      test(`member instant visibility omits display arrays; editor explicitly saves ${locale} ${width}`, async ({ page, context }) => {
        const guard = await protect(context)
        await page.setViewportSize({ width, height: 900 })
        await visit(page, "/member/sources/modules", locale)
        await connected(page, "main form[data-controller='auto-submit']", "auto-submit")
        const row = page.locator("main form[data-controller='auto-submit']").first()
        const edit = await row.locator("a").getAttribute("href")
        const action = new URL(await row.getAttribute("action"), BASE).pathname
        guard.handlers.set(action, () => ({ status: 204, body: "" }))
        const checked = await row.getByRole("checkbox").isChecked()
        await row.getByRole("checkbox").setChecked(!checked)
        await expect.poll(() => guard.writes.length).toBe(1)
        const toggle = params(guard.writes[0])
        expect(toggle.get("_method")).toBe("patch")
        expect(toggle.getAll("member_settings[rows][0][enabled]").at(-1)).toBe(checked ? "0" : "1")
        expect([...toggle.keys()].filter(k => k.includes("visible_"))).toEqual([])
        expect([...toggle.keys()].filter(k => k.startsWith("member_settings"))).toEqual(expect.arrayContaining([
          "member_settings[rows][0][surface_key]", "member_settings[rows][0][enabled]"
        ]))
        await visit(page, edit, locale)
        const form = page.locator("main form")
        const original = await payload(page, form)
        await form.locator("input[name='member_settings[rows][0][label]']").fill("QA draft portal")
        expect(guard.writes).toHaveLength(1)
        await page.locator("main details").evaluateAll(nodes => nodes.forEach(n => { n.open = true }))
        await fits(page, "member expanded display form")
        const entry = await interceptedSubmit(page, guard, form, submit(form))
        const saved = params(entry)
        expect(saved.get("member_settings[rows][0][label]")).toBe("QA draft portal")
        for (const key of ["visible_column_keys", "visible_section_keys", "visible_detail_row_keys"]) {
          const matching = original.filter(([name]) => name.includes(key))
          for (const [name] of matching) expect(saved.getAll(name)).toEqual(original.filter(([n]) => n === name).map(([, v]) => v))
        }
        await visit(page, edit, locale)
        expect(await payload(page, page.locator("main form"))).toEqual(original)
        expect(guard.unexpected).toEqual([])
      })

      test(`AI and security explicitly save; email and SMS limits remain platform-managed ${locale} ${width}`, async ({ page, context }) => {
        const guard = await protect(context)
        await page.setViewportSize({ width, height: 900 })
        for (const path of ["/modules/ai_assistant", "/modules/authentication"]) {
          await visit(page, path, locale)
          const forms = page.locator("main form")
          await expect(forms).toHaveCount(1)
          const primary = forms.first()
          const fields = primary.locator("input:not([type=hidden]):not([type=submit]),select")
          expect(await fields.count()).toBeGreaterThan(0)
          const original = await payload(page, primary)
          const count = guard.writes.length
          const field = fields.first()
          if (await field.evaluate(e => e.tagName === "SELECT")) {
            const options = await field.locator("option").evaluateAll(nodes => nodes.map(n => n.value).filter(Boolean))
            const current = await field.inputValue()
            await field.selectOption(options.find(value => value !== current) || options[0])
          } else {
            await field.fill("125")
          }
          expect(guard.writes).toHaveLength(count)
          const entry = await interceptedSubmit(page, guard, primary, submit(primary))
          const endpoints = { "/modules/ai_assistant": "/modules/ai_assistants", "/modules/emails/daily_cap": "/modules/emails", "/modules/sms/daily_cap": "/modules/sms", "/modules/authentication": "/modules/authentications" }
          expect(entry.path).toBe(ROOT + endpoints[path])
          expect([...params(entry).keys()].some(k => k.includes("exit_landing_page"))).toBe(false)
          await visit(page, path, locale)
          expect(await payload(page, page.locator("main form").first())).toEqual(original)
          await expect(page.locator("main [name*='exit_landing_page']")).toHaveCount(0)
        }
        for (const path of ["/modules/emails/daily_cap", "/modules/sms/daily_cap"]) {
          await visit(page, path, locale)
          await expect(page.locator("main form")).toHaveCount(0)
          await expect(page.locator("#main-content")).toContainText(locale === "en"
            ? "The platform owner manages this limit for your organization."
            : "此组织的限额由平台所有者管理。")
          await fits(page, `platform-managed ${path}`)
        }
        for (const path of ["sign_up", "forget_password"]) {
          await visit(page, `/modules/authentication/${path}`, locale)
          const form = page.locator("main form")
          const count = guard.writes.length
          await form.locator("select").selectOption("false")
          expect(guard.writes).toHaveLength(count)
          const entry = await interceptedSubmit(page, guard, form, submit(form))
          expect(params(entry).get("setting[enabled]")).toBe("false")
        }
        expect(guard.unexpected).toEqual([])
      })

      test(`provider saved-connection feedback, environment navigation and instant toggle rollback ${locale} ${width}`, async ({ page, context }) => {
        const guard = await protect(context)
        await page.setViewportSize({ width, height: 900 })
        registerFixture(guard, "payment-sandbox", locale)
        registerFixture(guard, "payment-production", locale)
        await fixture(page, guard, "payment-providers", locale)
        const edit = await page.locator("main a[href$='/edit']").first().getAttribute("href")
        const toggle = page.locator("main [data-controller='payments--gateway-toggle']").filter({ has: page.locator("input:not([disabled])") }).first()
        await connected(page, "main [data-controller='payments--gateway-toggle']", "payments--gateway-toggle")
        const action = await toggle.getAttribute("data-payments--gateway-toggle-url-value")
        const originalState = await toggle.locator("input").isChecked()
        guard.handlers.set(new URL(action, BASE).pathname, () => ({ status: 422, contentType: "application/json", body: JSON.stringify({ errors: ["QA isolated rejection"] }) }))
        await toggle.locator("label").click()
        await expect.poll(() => guard.writes.length).toBe(1)
        expect(JSON.parse(guard.writes[0].body)).toEqual({ payment_merchant_account: { status: originalState ? "disabled" : "active" } })
        await expect(toggle.locator("input")).toBeChecked({ checked: originalState })
        await fixture(page, guard, "payment-sandbox", locale)
        expect(new URL(edit, BASE).pathname).toBe(new URL(page.url()).pathname)
        await connected(page, "form[data-controller='payments--gateway-config']", "payments--gateway-config")
        const form = page.locator("form[data-controller='payments--gateway-config']")
        const merchant = form.locator("input[name='payment_merchant_account[merchant_id]']")
        await merchant.fill("QA_UNSAVED_ACCOUNT")
        const testPath = await form.getAttribute("data-payments--gateway-config-test-url-value")
        const result = form.locator("[data-payments--gateway-config-target='result']")
        guard.handlers.set(new URL(testPath, BASE).pathname, () => ({ contentType: "application/json", body: JSON.stringify({ ok: true, verified_at_label: "2026-09-23 12:00 UTC" }) }))
        await form.locator("[data-payments--gateway-config-target='testButton']").click()
        await expect(result).toContainText(await form.getAttribute("data-payments--gateway-config-verified-label-value"))
        expect(guard.writes.at(-1).body).toBeNull()
        expect(guard.writes.at(-1).headers.accept).toBe("application/json")
        await expect(merchant).toHaveValue("QA_UNSAVED_ACCOUNT")
        guard.handlers.set(new URL(testPath, BASE).pathname, () => ({ status: 422, contentType: "application/json", body: JSON.stringify({ ok: false, message: "QA saved connection rejected" }) }))
        await form.locator("[data-payments--gateway-config-target='testButton']").click()
        await expect(result).toContainText("QA saved connection rejected")
        await screenshot(page, `payment-connection-error-${locale}-${width}`)
        const save = await interceptedSubmit(page, guard, form, submit(form))
        expect(params(save).get("payment_merchant_account[merchant_id]")).toBe("QA_UNSAVED_ACCOUNT")
        expect(params(save).has("payment_merchant_account[status]")).toBe(false)
        await fixture(page, guard, "payment-sandbox", locale)
        const next = page.locator("main a[data-mode]")
        const mode = await next.getAttribute("data-mode")
        await next.click()
        await expect(page.locator("main [data-mode][aria-current='page']")).toHaveAttribute("data-mode", mode)
        expect(guard.unexpected).toEqual([])
      })

      test(`public page protection search and custom versus instant preset saves ${locale} ${width}`, async ({ page, context }) => {
        const guard = await protect(context)
        await page.setViewportSize({ width, height: 900 })
        await fixture(page, guard, "public-protection", locale)
        await connected(page, "form[data-controller='captcha-throttle-picker']", "captcha-throttle-picker")
        const search = page.locator("main input[type=search]")
        await search.fill("qa-no-such-public-page")
        await expect(page.locator("main form[data-controller='captcha-throttle-picker']:visible")).toHaveCount(0)
        await search.fill("")
        const form = page.locator("main form[data-controller='captcha-throttle-picker']").first()
        await expect(form).toBeVisible()
        const action = new URL(await form.getAttribute("action"), BASE).pathname
        guard.handlers.set(action, () => ({ status: 204, body: "" }))
        await form.locator("[data-captcha-throttle-picker-target='display']").click()
        // Close Chromium's native picker before selecting its DOM option.
        await page.keyboard.press("Escape")
        const choice = form.locator("[data-captcha-throttle-picker-target='choice']")
        await choice.selectOption("custom")
        await expect(form.locator("[data-captcha-throttle-picker-target='customFields']")).toBeVisible()
        await form.locator("input[name=limit_count]").fill("0")
        await form.locator("input[name=period_minutes]").fill("3")
        await form.locator("[data-action='click->captcha-throttle-picker#apply']").click()
        expect(guard.writes).toEqual([])
        await form.locator("input[name=limit_count]").fill("7")
        await fits(page, "custom public-page protection controls")
        await screenshot(page, `captcha-custom-${locale}-${width}`)
        const entry = await interceptedSubmit(page, guard, form, form.locator("[data-action='click->captcha-throttle-picker#apply']"))
        expect(params(entry).get("preset")).toBe("custom")
        expect(params(entry).get("limit_count")).toBe("7")
        expect(params(entry).get("period_minutes")).toBe("3")
        await fixture(page, guard, "public-protection", locale)
        await connected(page, "form[data-controller='captcha-throttle-picker']", "captcha-throttle-picker")
        const fresh = page.locator("main form[data-controller='captcha-throttle-picker']").first()
        const preset = fresh.locator("[data-captcha-throttle-picker-target='choice']")
        const current = await preset.inputValue()
        const next = await preset.locator("option").evaluateAll((nodes, current) => nodes.map(n => n.value).find(value => value && value !== current && !["custom", "skip"].includes(value)), current)
        expect(next).toBeTruthy()
        await fresh.locator("[data-captcha-throttle-picker-target='display']").click()
        await page.keyboard.press("Escape")
        await preset.selectOption(next)
        await expect.poll(() => guard.writes.length).toBe(2)
        expect(params(guard.writes.at(-1)).get("preset")).toBe(next)
        expect(guard.unexpected).toEqual([])
      })

      test(`email bulk field choices and single reserved-role access dialog reject safely ${locale} ${width}`, async ({ page, context }) => {
        const guard = await protect(context)
        await page.setViewportSize({ width, height: 900 })
        await visit(page, "/modules/emails/template_tokens/new", locale)
        await connected(page, "form[data-controller='email-template-token-bulk']", "email-template-token-bulk")
        const form = page.locator("main form")
        const groups = form.locator("[data-email-template-token-bulk-target='group']")
        const available = groups.filter({ has: page.locator("[data-email-template-token-bulk-target='checkbox']") }).first()
        const entity = await available.getAttribute("data-entity-id")
        await expect(submit(form)).toBeDisabled()
        await form.locator("select[name='emails_template_token[entity_id]']").selectOption(entity)
        await expect(available).toBeVisible()
        const fields = available.locator("[data-email-template-token-bulk-target='checkbox']")
        expect(await fields.count()).toBeGreaterThan(0)
        expect(await fields.evaluateAll(nodes => nodes.every(node => node.checked && !node.disabled))).toBe(true)
        await available.locator("[data-action='email-template-token-bulk#clearAll']").click()
        await expect(submit(form)).toBeDisabled()
        await available.locator("[data-action='email-template-token-bulk#selectAll']").click()
        await expect(submit(form)).toBeEnabled()
        if (await fields.count() > 1) await fields.last().uncheck()
        const label = available.locator("input[type=text]").first()
        await label.fill("QA draft field")
        const count = await fields.evaluateAll(nodes => nodes.filter(node => node.checked).length)
        await expect(available.locator("[data-email-template-token-bulk-target='count']")).toHaveText(
          (await form.getAttribute("data-email-template-token-bulk-count-label-value")).replace("{count}", count))
        const draft = await payload(page, form)
        await fits(page, `bulk personalization ${locale} ${width}`)
        expect(guard.writes).toEqual([])
        const entry = await interceptedSubmit(page, guard, form, submit(form))
        expect(params(entry).get("emails_template_token[entity_id]")).toBe(entity)
        for (const name of new Set(draft.map(([name]) => name))) {
          expect(params(entry).getAll(name), name).toEqual(draft.filter(([key]) => key === name).map(([, value]) => value))
        }
        await fixture(page, guard, "user-access", locale)
        await connected(page, "button[data-controller='user-role-dialog']", "user-role-dialog")
        const trigger = page.locator("button[data-controller='user-role-dialog']").first()
        await trigger.click()
        const dialog = page.getByRole("dialog", { name: locale === "en" ? "Edit access" : "编辑访问权限" })
        await expect(dialog).toBeVisible()
        await expect(dialog).toContainText(await trigger.getAttribute("data-user-role-dialog-user-name-value"))
        const choices = dialog.getByRole("checkbox")
        const roles = JSON.parse(await trigger.getAttribute("data-user-role-dialog-roles-value"))
        expect(roles.map(role => role.key).sort()).toEqual(["admin", "member", "owner"])
        for (const choice of await choices.all()) await choice.uncheck()
        await dialog.locator(`input[value='${roles.find(role => role.key === "member").id}']`).check()
        const selected = await choices.evaluateAll(nodes => nodes.filter(n => n.checked).map(n => Number(n.value)))
        expect(selected).toHaveLength(1)
        const action = await trigger.getAttribute("data-user-role-dialog-submit-url-value")
        guard.handlers.set(new URL(action, BASE).pathname, () => ({ status: 422, contentType: "application/json", body: JSON.stringify({ errors: ["QA isolated rejection"] }) }))
        const failure = await handleDialog(page, () => dialog.locator("button[data-action='save']").click())
        expect(failure.message).toContain("QA isolated rejection")
        expect(JSON.parse(guard.writes.at(-1).body)).toEqual({ user_id: Number(await trigger.getAttribute("data-user-role-dialog-user-id-value")), role_ids: selected })
        await expect(dialog).toBeVisible()
        await screenshot(page, `user-access-dialog-${locale}-${width}`)
        await page.keyboard.press("Escape")
        await expect(dialog).toBeHidden()
        expect(guard.unexpected).toEqual([])
      })

      test(`website theme/footer drafts and starter confirmation stay separate ${locale} ${width}`, async ({ page, context }) => {
        const guard = await protect(context)
        await page.setViewportSize({ width, height: 900 })
        await visit(page, "/modules/website", locale)
        await connected(page, "[data-controller='website-theme-picker']", "website-theme-picker")
        const form = page.locator("form").filter({ has: page.locator("#website_name") })
        const original = await payload(page, form)
        const preview = page.locator("[data-theme-preview-swatch]")
        const old = await preview.getAttribute("data-appearance")
        const appearance = form.locator("input[data-token='appearance']:not(:checked)").first()
        const value = await appearance.inputValue()
        await appearance.locator("..").click()
        await expect(preview).toHaveAttribute("data-appearance", value)
        expect(value).not.toBe(old)
        await preview.scrollIntoViewIfNeeded()
        await screenshot(page, `website-theme-${locale}-${width}`)
        await form.locator("#website_name").fill("QA unsaved website")
        await form.locator("#website_footer_column_new_heading").fill("QA links")
        await form.locator("#website_footer_column_new_link_label").fill("Contact")
        await form.locator("#website_footer_column_new_link_url").fill("/contact")
        await page.locator("#website-settings-footer").scrollIntoViewIfNeeded()
        await screenshot(page, `website-footer-${locale}-${width}`)
        expect(guard.writes).toEqual([])
        const starter = page.locator("[data-skeleton-replace]")
        await starter.locator("summary").click()
        const replace = starter.locator("form").first()
        expect(await replace.getAttribute("action")).not.toBe(await form.getAttribute("action"))
        await expect(replace).toHaveAttribute("aria-describedby", "website-replacement-consequences")
        expect(await replace.getAttribute("data-turbo-confirm")).toBeTruthy()
        const confirm = await handleDialog(page, () => replace.getByRole("button").click())
        expect(confirm.type).toBe("confirm")
        expect(confirm.message).toBe(await replace.getAttribute("data-turbo-confirm"))
        expect(guard.writes).toEqual([])
        await screenshot(page, `website-starter-${locale}-${width}`)
        const save = page.locator(`button[form='${await form.getAttribute("id")}']`)
        const entry = await interceptedSubmit(page, guard, form, save)
        expect(params(entry).get("website[name]")).toBe("QA unsaved website")
        expect(params(entry).get("website[theme][appearance]")).toBe(value)
        expect(params(entry).has("skeleton_key")).toBe(false)
        await visit(page, "/modules/website", locale)
        expect(await payload(page, page.locator("form").filter({ has: page.locator("#website_name") }))).toEqual(original)
        expect(guard.unexpected).toEqual([])
      })
    }
  }
})
