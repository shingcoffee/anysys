  def contribute
    return [] if customer_id.blank?

    modules = FeatureModules::NavigationOrder.sort(FeatureModules::Module.available_for_customer(customer_id).by_name)
    sections = FeatureModules::NavigationOrder.by_section(modules, &:key)

    # Enable/disable lives only under Maintenance / Modules — never in the
    # Modules sidebar, even for the platform owner.
    [overview_node, *sections.flat_map { |section, fms| [category_node(section), *fms.map { |fm| module_group(fm) }] }]
  end

  private

  def category_node(section)
    SidebarNode.new(
      key: "modules.category.#{section}",
      label: FeatureModules::NavigationOrder.section_label(section),
      menu_item: MENU_ITEM,
      category: true
    )
  end

  def overview_node
    SidebarNode.new(
      key: "modules.overview",
      label: I18n.t("admin_modules.nav.overview"),
      menu_item: MENU_ITEM,
      path: "/#{customer_id}/admin/modules",
      icon: OVERVIEW_ICON,
      description: I18n.t("admin_modules.index.description")
    )
  end

  # Each enabled module has a guide, including settings-only modules. Settings
  # actions remain in the Settings tab, separate from record entries here.
  def module_group(fm)
    entries = fm.registration_class.sidebar_contributions(context)[:entries].to_a
    children = [howto_node(fm), *entries.map { |c| entry_node(c, fm) }]

    SidebarNode.new(
      key: "modules.#{fm.key}",
      label: fm.display_name,
      menu_item: MENU_ITEM,
      icon: module_icon(fm.key),
      tone: fm.key,
      section_root: true,
      description: blurb_for(fm),
      children: children
    )
  end

  def howto_node(fm)
    SidebarNode.new(
      key: "modules.#{fm.key}.howto",
      label: I18n.t("admin_modules.index.howto.title"),
      menu_item: MENU_ITEM,
      path: Rails.application.routes.url_helpers.admin_module_howto_path(customer_id, fm.key),
      icon: ENTRY_ICONS["howto"]
    )
  end

  def entry_node(contribution, fm)
    node = contribution.to_sidebar_node(menu_item: MENU_ITEM, module_key: fm.key, customer_id: customer_id)
    return node if contribution.children.any?

    node.with(icon: contribution.icon.presence || ENTRY_ICONS[contribution.entry_key])
  end

  def module_icon(key)
    Admin::Maintenance::Platform::ModuleSettingsHelper::MODULE_ICON_PATHS.fetch(
      key.to_s,
      Admin::Maintenance::Platform::ModuleSettingsHelper::DEFAULT_MODULE_ICON_PATH
    )
  end

  def blurb_for(fm)
    key = "admin_misc.dashboard.modules.blurbs.#{fm.key}"
    return I18n.t(key) if I18n.exists?(key)

    I18n.t("admin_misc.dashboard.modules.blurbs.fallback", name: fm.display_name)
  end
