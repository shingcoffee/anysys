# frozen_string_literal: true

module Admin
module Maintenance
  class EntitiesController < ApplicationController
    dashboard_menu_item :maintenance
    include SoftDeletableController
    include Listable
    include SharedResourceMode

    soft_deletable Entity

    InvalidDefinition = Class.new(StandardError)
    rescue_from InvalidDefinition, with: :render_invalid_definition
    helper_method :admin_maintenance_entity_path, :entity_grouping?

    before_action :find_entity, only: %i[show edit update destroy]
    before_action :require_entity_author!, only: %i[new create]
    # Tenant-path edits of a shared entity are allowed — they fork into that
    # customer's override (see entity_params + Versionable), including for
    # 81721200. Destroying a shared entity is Shared Resources (path) only.
    guard_shared_global_writes :@entity, only: :destroy, json_error: "shared_entity_readonly" do
      admin_maintenance_entities_path(current_customer_id)
    end

    def index
      @columns = [
        { key: :display_label,    label: I18n.t("maint_core.entities.form.display_label"), sortable: true, searchable: true,
          subtitle: ->(e) { e.description.to_s.presence },
          leading: ->(e) { e.bridge_entity? ? { icon: :document, tone: :info } : { icon: :document, tone: :accent } } },
        { key: :kind,             label: I18n.t("common.labels.kind"),       type: :badge, sortable: false, searchable: false,
          badge: ->(e) { e.bridge_entity? ? { variant: :info, label: I18n.t("common.labels.bridge") } : { variant: :default, label: I18n.t("common.labels.normal") } },
          cell:  ->(e) { e.bridge_entity? ? I18n.t("common.labels.bridge") : I18n.t("common.labels.normal") } },
        { key: :attributes_count, label: I18n.t("common.labels.attributes"), type: :number, sortable: false, searchable: false,
          cell: ->(e) { (e.property_schema_json || []).length } },
        { key: :current_version,  label: I18n.t("common.labels.current_version"), type: :text, sortable: false, searchable: false,
          cell: ->(e) { (v = e.display_current_version) ? "v#{v.version_number}" : I18n.t("common.labels.em_dash") } },
        { key: :updated_at,       label: I18n.t("common.labels.updated_at"),    type: :datetime, sortable: true }
      ]
      base = definition_scope(Entity).includes(:entity_versions, current_version: :content)
      base = base.by_name
      @grouped_view = entity_grouping? && params[:view] != "table"
      table_scope = params[:show_bridge] == "true" ? base : base.non_bridge

      respond_to do |format|
        format.html do
          if @grouped_view
            @sections = ::EntityDomains::Layout.call(customer_id: current_customer_id, entities: base.to_a)
            @journeys = Journey.for_customer(current_customer_id).by_name.to_a
          else
            result = ModuleEntriesResolver.call(
              scope: table_scope, columns: @columns,
              params: params.permit(:q, :sort, :dir, :page, :show_bridge).to_h.symbolize_keys
            )
            @rows       = result[:rows]
            @entities   = @rows
            @pagination = result[:pagination]
          end
        end
        format.json do
          entities = table_scope.by_name
          entities = entities.search_by_display_label(params[:search]) if params[:search].present?
          render json: entities.map { |entity| reference_target_item(entity) }
        end
      end
    end

    def show
      validate_loaded_definition!
      @model_code    = ModelGenerator.new(@entity).generate
      @contract_code = ContractGenerator.new(@entity).generate

      respond_to do |format|
        format.html
        format.json { render json: @entity.as_palette_item.merge(referenced_template: @entity.referenced_template) }
      end
    end

    def new
      @entity = Entity.new
      apply_create_identity!(@entity)
      prepare_domain_choice(params[:domain_id])
    end

    def edit
      if params[:version].present?
        @editing_version = editable_version(params[:version])
        snapshot = JSON.parse(@editing_version.payload)
        raise InvalidDefinition, t("routes_audit.invalid_definition") unless snapshot.is_a?(Hash)
        validate_definition_shapes!(snapshot)
        @entity = ::Entities::VersionHydrator.hydrate(@entity, @editing_version)
        @entity.referenced_template = snapshot["referenced_template"]
      end
      validate_loaded_definition!
    rescue JSON::ParserError, TypeError
      raise InvalidDefinition, t("routes_audit.invalid_definition")
    end

    # Carry historical lineage in the form action generated by the existing
    # entity partial; do not change the builder render or any global URL defaults.
    def admin_maintenance_entity_path(*args, **options)
      options = options.merge(based_on_version_id: @editing_version.id) if @editing_version
      super(*args, **options)
    end
    private :admin_maintenance_entity_path

    def create
      @entity = Entity.new(entity_params)
      apply_create_identity!(@entity)
      @entity.commit_based_on_version_id = params[:based_on_version_id]
      domain = prepare_domain_choice(params[:entity_domain_id])

      guard = Billing::Quota::Guard.check(customer: current_customer, item_key: "entity")
      unless skip_quota_for_shared_create?(@entity) || guard.allowed?
        @entity.errors.add(:base, guard.message)
        flash.now[:alert] = guard.message
        respond_to do |format|
          format.html { render :new, status: :unprocessable_entity }
          format.json { render json: { error: guard.message }, status: :unprocessable_entity }
        end
        return
      end

      saved = false
      if entity_domain_choice? && domain.nil?
        @entity.errors.add(:base, t("maint_core.entity_domains.errors.domain_required"))
      else
        ActiveRecord::Base.transaction do
          if @entity.save
            saved = @entity.sync_bridge_entities!
            raise ActiveRecord::Rollback unless saved

            ::EntityDomains::Memberships.place!(@entity, domain) if domain
          end
        end
      end

      if saved
        # Version snapshot is created automatically by Versionable's after_save
        # auto-commit; no explicit call needed here.
        respond_to do |format|
          format.html do
            redirect_to admin_maintenance_entities_path(current_customer_id, domain_id: domain&.id),
                        notice: t("maint_core.flash.entities.created")
          end
          format.json { render json: @entity.as_palette_item, status: :created }
        end
      else
        respond_to do |format|
          format.html { render :new, status: :unprocessable_entity }
          format.json { render json: { errors: @entity.errors.full_messages }, status: :unprocessable_entity }
        end
      end
    end

    def update
      @entity.commit_based_on_version_id = editable_version(params[:based_on_version_id]).id if params[:based_on_version_id].present?
      saved = false
      ActiveRecord::Base.transaction do
        if @entity.update(entity_params)
          saved = @entity.sync_bridge_entities!
          raise ActiveRecord::Rollback unless saved

          ::EntityDomains::Memberships.place_bridges!(@entity)
        end
      end

      if saved
        # Version snapshot (if the definition changed) is created automatically
        # by Versionable's after_save auto-commit; identity-only edits no-op.
        respond_to do |format|
          format.html { redirect_to admin_maintenance_entity_path(current_customer_id, @entity), notice: t("maint_core.flash.entities.updated") }
          format.json { render json: @entity.as_palette_item }
        end
      else
        respond_to do |format|
          format.html { render :edit, status: :unprocessable_entity }
          format.json { render json: { errors: @entity.errors.full_messages }, status: :unprocessable_entity }
        end
      end
    end

    def destroy
      if @entity.soft_delete
        respond_to do |format|
          format.html { redirect_to admin_maintenance_entities_path(current_customer_id), notice: destroyed_notice }
          format.json { head :no_content }
        end
      else
        respond_to do |format|
          format.html { redirect_to admin_maintenance_entities_path(current_customer_id), alert: @entity.errors.full_messages.join(", ") }
          format.json { render json: { errors: @entity.errors.full_messages }, status: :unprocessable_entity }
        end
      end
    end

    def template_fields
      key      = params[:key]
      template = PageLayoutTemplates.find(key)

      if template.nil?
        render json: { error: t("maint_core.flash.entities.template_not_found") }, status: :not_found
        return
      end

      extracted = TemplateFieldExtractor.call(template)
      render json: { fields: extracted[:fields], groups: extracted[:groups], template: template }
    end

    def base_model_fields
      fields = EntityDefinitions::Capabilities.base_model_fields(current_customer.id, params[:model].to_s)
      render json: { fields: fields }
    end

    private

    # Domains belong to a tenant, so Shared Resources (which lists
    # only shared rows) never shows them.
    def entity_grouping?
      !shared_resources_mode? && EntityDomainVisibility.allowed?(current_user)
    end

    def find_entity
      @entity = definition_scope(Entity).find(params[:id])
    end

    # Entities are created by hand only by the platform owner; tenant admins
    # create them through the assistant.
    def require_entity_author!
      return if current_user.platform_owner?

      raise CanCan::AccessDenied, t("common.errors.authorization.platform_owner_required")
    end

    # A customer-owned entity is created into one of the customer's domains;
    # a shared entity (Shared Resources) belongs to no customer's domain.
    def entity_domain_choice? = !shared_resources_mode?

    def prepare_domain_choice(domain_id)
      return unless entity_domain_choice?

      @domains = EntityDomain.for_customer(current_customer_id).by_name.to_a
      domain = @domains.find { |candidate| candidate.id.to_s == domain_id.to_s }
      @entity_domain_id = domain&.id || (@domains.first.id if @domains.one?)
      domain
    end

    def destroyed_notice
      notices = [t("maint_core.flash.entities.deleted")]
      count = @entity.forms_taken_offline
      notices << t("maint_core.flash.entities.forms_taken_offline", count: count) if count.positive?
      notices.join(" ")
    end

    # Versioned definition body — the only thing a customer override may change.
    DEFINITION_KEYS = %i[icon color description default_properties property_schema
                         attribute_groups referenced_template].freeze
    # Global identity — editable only by the platform owner (or on a
    # customer-specific entity the customer owns).
    IDENTITY_KEYS = %i[name display_label extended_model associations].freeze

    def entity_params
      keys = permitted_entity_keys
      raw = params.require(:entity)
      unless raw.is_a?(ActionController::Parameters)
        raise InvalidDefinition, t("routes_audit.invalid_definition")
      end

      permitted = raw.permit(*keys)
      # These are explicitly whitelisted definition bags, not model attributes.
      # Their nested structure is validated by the shared Reform contract.
      structured = raw.slice(*(::Entities::Contracts::Definition::JSON_TYPES.keys & keys)).permit!.to_h
      parsed = validate_definition_shapes!(structured)
      parsed.each do |key, value|
        permitted[key] = value.nil? ? raw[key] : value.to_json
      end
      permitted
    end

    def validate_loaded_definition!
      attributes = ::Entities::Contracts::Definition::JSON_TYPES.keys.to_h do |key|
        reader = key == :referenced_template ? key : "#{key}_json"
        [key, @entity.public_send(reader)]
      end
      validate_definition_shapes!(attributes)
    end

    def validate_definition_shapes!(attributes)
      form = ::Entities::Contracts::Definition.new(OpenStruct.new)
      raise InvalidDefinition, form.errors.full_messages.to_sentence unless form.validate(definition: attributes)

      form.normalized_attributes
    end

    def editable_version(id)
      unless (id.is_a?(String) || id.is_a?(Integer)) && id.to_s.match?(/\A[1-9]\d*\z/)
        raise ActiveRecord::RecordNotFound
      end
      @entity.current_line_versions.find_by(id: id) ||
        (@entity.shared? && @entity.versions_relation.where(customer_id: nil).find_by(id: id)) ||
        raise(ActiveRecord::RecordNotFound)
    end

    def render_invalid_definition(error)
      respond_to do |format|
        format.html { render plain: error.message, status: :unprocessable_entity }
        format.json { render json: { errors: [error.message] }, status: :unprocessable_entity }
      end
    end

    # A tenant-path edit of a SHARED entity may only change the versioned
    # definition body (the edit forks into a per-customer override, including
    # for customer 81721200). Global identity is editable only from Shared
    # Resources, or on a customer-owned entity / create.
    def permitted_entity_keys
      return DEFINITION_KEYS if tenant_override?(@entity)

      DEFINITION_KEYS + IDENTITY_KEYS
    end

    # The palette item, with each attribute marked by whether it may label a
    # reference; the editor offers only those as display fields.
    def reference_target_item(entity)
      item = entity.as_palette_item
      item.merge(property_schema: item[:property_schema].map do |attribute|
        attribute.is_a?(Hash) ? attribute.merge("labelable" => ::Entities::ReferenceLabels.labelable?(attribute)) : attribute
      end)
    end
  end
end
